// scripts/gen-landing-land-mask.mjs
/**
 * Rasterise Natural Earth 110m land (public domain) into the 1-bit equirectangular land mask that the landing hero
 * globe samples its dots from. Run once when the source data or the grid changes:
 *
 *   node scripts/gen-landing-land-mask.mjs <path/to/ne_110m_land.geojson> > src/landing/hero-globe.landData.js
 *
 * Source: https://raw.githubusercontent.com/nvkelso/natural-earth-vector/<commit>/geojson/ne_110m_land.geojson
 * (commit and licence are recorded in DATA_SOURCES.md). Format: see `decodeLandMask` in hero-globe.landMask.js.
 */
import { readFileSync } from 'node:fs';

const WIDTH = 720;
const HEIGHT = 360;
const RUN_DIGITS = 2;

/** Even-odd ray cast of (x, y) against every ring of one polygon (outer ring first, then holes). */
function insidePolygon(rings, x, y) {
  let inside = false;
  for (const ring of rings) {
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [xi, yi] = ring[i];
      const [xj, yj] = ring[j];
      if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
    }
  }
  return inside;
}

function polygonsOf(geojson) {
  return geojson.features.flatMap(({ geometry }) => (geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates));
}

/** One mask row as alternating water/land run lengths, starting with water (a zero-length first run is allowed). */
function rowRuns(polygons, y) {
  const runs = [];
  let current = false;
  let length = 0;
  for (let col = 0; col < WIDTH; col++) {
    const x = ((col + 0.5) / WIDTH) * 360 - 180;
    const land = polygons.some((rings) => insidePolygon(rings, x, y));
    if (land !== current) {
      runs.push(length);
      current = land;
      length = 0;
    }
    length++;
  }
  runs.push(length);
  return runs;
}

function main(path) {
  if (!path) throw new Error('usage: node scripts/gen-landing-land-mask.mjs <ne_110m_land.geojson>');
  const polygons = polygonsOf(JSON.parse(readFileSync(path, 'utf8')));
  let encoded = '';
  for (let row = 0; row < HEIGHT; row++) {
    const y = 90 - ((row + 0.5) / HEIGHT) * 180;
    for (const run of rowRuns(polygons, y)) encoded += run.toString(36).padStart(RUN_DIGITS, '0');
  }
  process.stdout.write(
    `// Generated by scripts/gen-landing-land-mask.mjs from Natural Earth 110m land (public domain). Do not edit.\n` +
      `export const LAND_MASK = { width: ${WIDTH}, height: ${HEIGHT}, runs: '${encoded}' };\n`,
  );
}

main(process.argv[2]);
